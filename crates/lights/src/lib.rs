#[cfg(test)]
mod ui_constants {
    /// The Lights tab needs the setup's limits. ts-rs exports types only,
    /// so this writes them next to the generated types.
    #[test]
    fn export_constants_for_the_ui() {
        let Ok(dir) = std::env::var("TS_RS_EXPORT_DIR") else { return };
        use crate::setup::*;
        let constants = [
            ("UNIVERSE_SIZE", crate::UNIVERSE_SIZE.to_string()),
            ("MAX_FIXTURES", MAX_FIXTURES.to_string()),
            ("MAX_FIXTURE_CHANNELS", MAX_FIXTURE_CHANNELS.to_string()),
            ("MAX_LOOKS", MAX_LOOKS.to_string()),
            ("MAX_LOOK_COLORS", MAX_LOOK_COLORS.to_string()),
            ("MAX_LOOK_CHANNELS", MAX_LOOK_CHANNELS.to_string()),
            ("MAX_LIGHTS_NAME_CHARS", MAX_LIGHTS_NAME_CHARS.to_string()),
            ("MIN_EFFECT_MS", MIN_EFFECT_MS.to_string()),
            ("MAX_EFFECT_MS", MAX_EFFECT_MS.to_string()),
            ("MAX_FADE_MS", MAX_FADE_MS.to_string()),
            ("MIN_FLASH_MS", MIN_FLASH_MS.to_string()),
            ("MAX_FLASH_MS", MAX_FLASH_MS.to_string()),
            ("MAX_ARTNET_UNIVERSE", MAX_ARTNET_UNIVERSE.to_string()),
            ("MIN_SACN_UNIVERSE", MIN_SACN_UNIVERSE.to_string()),
            ("MAX_SACN_UNIVERSE", MAX_SACN_UNIVERSE.to_string()),
            ("FIRST_STAGE_NOTE", crate::signals::FIRST_STAGE_NOTE.to_string()),
            ("FIRST_CUE_NOTE", crate::signals::FIRST_CUE_NOTE.to_string()),
            ("SHOW_STARTED_NOTE", crate::signals::SHOW_STARTED_NOTE.to_string()),
            ("SHOW_ENDED_NOTE", crate::signals::SHOW_ENDED_NOTE.to_string()),
            ("BUZZ_NOTE", crate::signals::BUZZ_NOTE.to_string()),
        ];
        let mut ts = String::from("// Generated by `cargo test` from crates/lights. Do not edit this file manually.\n\n");
        for (name, value) in constants {
            ts.push_str(&format!("export const {name} = {value};\n"));
        }
        std::fs::write(std::path::Path::new(&dir).join("LightsConstants.ts"), ts).unwrap();
    }
}
