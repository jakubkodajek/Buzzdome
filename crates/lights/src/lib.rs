//! Stage lights that follow the show, and messages that tell outside
//! programs what happens in it (spec section 12).
//!
//! The parts, each testable without a device:
//!
//! - [`setup`]: the venue's lights as the quizmaster sets them up: the
//!   fixtures and their DMX channels, the looks, which look each stage of
//!   the show takes, the flashes for its cues, and where messages go.
//! - [`look`]: draws a look on the fixtures at a moment (colours, effects,
//!   intensity) into a DMX universe.
//! - [`desk`]: which look shows now (stage, flash, hold, blackout) and the
//!   fades between them.
//! - [`dmx`]: the outputs a universe goes through: USB-DMX interfaces
//!   (Enttec DMX USB Pro, Enttec Open DMX USB, SoundSwitch Micro DMX) and
//!   the network (Art-Net, sACN).
//! - [`signals`]: show events as OSC messages over UDP and as MIDI notes.
//! - [`engine`]: the lights thread, which sends a frame at a steady rate,
//!   reopens an output that failed and sends the messages, so the show
//!   thread never waits for a device.
//!
//! The show is never told what the lights did: they are a view of it, like
//! the projector, and a show resumed after a crash shows its stage's look
//! again. See `docs/design.md` section 7.

