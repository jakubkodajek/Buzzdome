#[cfg(test)]
mod ui_constants {
    /// The UI needs some of the core's constants. ts-rs exports types only,
    /// so this writes them next to the generated types.
    #[test]
    fn export_constants_for_the_ui() {
        let Ok(dir) = std::env::var("TS_RS_EXPORT_DIR") else { return };
        let constants = [
            ("MAX_ANSWERS", crate::MAX_ANSWERS.to_string()),
            ("MAX_EVERYONE_ANSWERS", crate::MAX_EVERYONE_ANSWERS.to_string()),
            ("MIN_EVERYONE_ANSWERS", crate::MIN_EVERYONE_ANSWERS.to_string()),
            ("DEFAULT_TIME_LIMIT_S", crate::DEFAULT_TIME_LIMIT_S.to_string()),
            ("DEFAULT_POINTS", crate::DEFAULT_POINTS.to_string()),
            ("MAX_POINTS", crate::MAX_POINTS.to_string()),
            ("MAX_TIME_LIMIT_S", crate::MAX_TIME_LIMIT_S.to_string()),
            ("FINAL_LAST_STEP", crate::game::FINAL_LAST_STEP.to_string()),
            ("MIN_GAIN_DB", crate::MIN_GAIN_DB.to_string()),
            ("MAX_GAIN_DB", crate::MAX_GAIN_DB.to_string()),
            ("DEFAULT_THEME_ID", serde_json::to_string(crate::DEFAULT_THEME_ID).unwrap()),
        ];
        let mut ts = String::from("// Generated by `cargo test` from crates/quiz-core. Do not edit this file manually.\n\n");
        for (name, value) in constants {
            ts.push_str(&format!("export const {name} = {value};\n"));
        }
        std::fs::write(std::path::Path::new(&dir).join("Constants.ts"), ts).unwrap();
    }
}
