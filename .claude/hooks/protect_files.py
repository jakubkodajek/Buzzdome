#!/usr/bin/env python3
"""PreToolUse hook for Edit|Write: a speed bump against edits to secrets,
lockfiles, generated files and the reference manual copies.

Exits 2 (block, stderr shown to the agent) for such a path. The path is
normalised against the project folder first, so `./` and `..` do not get
around it. Writes through Bash (`sed -i`, `>`) are not seen here; CI's
bindings check and `.gitignore` are the real guards.
"""

from __future__ import annotations

import fnmatch
import json
import os
import sys

# (patterns relative to the project folder, reason)
RULES: list[tuple[tuple[str, ...], str]] = [
    ((".env", ".env.*", "*/.env", "*/.env.*"), "secret file; edit .env.example instead"),
    (("*.pem", "*.key", "*id_rsa*", "*.p12", "*.pfx"), "private key material"),
    (("Cargo.lock", "*/package-lock.json"), "lockfile; change it with cargo or npm, not by hand"),
    (("app/src/bindings/*",), "generated by ts-rs; change the Rust type and run cargo test --workspace"),
    ((".github/agents/*", ".codex/agents/*", ".agents/skills/*"), "generated file; edit .claude/agents or .claude/skills and run python3 scripts/sync_agents.py"),
    (("replica/sources/*", "replica/screens/*", "replica/captures/*", "docs/index.md", "docs/solo.md", "docs/tips-and-tricks.md"), "reference manual copy or capture (clean room); never write or quote it"),
    (tuple(f"docs/{d}/*" for d in ("advanced", "analyzer", "assets", "hardware-installation", "installation", "javascripts", "legal", "live", "setup", "studio", "stylesheets", "troubleshooting")), "reference manual copy (clean room); our docs are the files directly in docs/ and docs/adr/"),
    ((".git/*",), "git internals"),
]


def main() -> None:
    try:
        data = json.load(sys.stdin)
    except ValueError:
        print("Blocked by .claude/hooks/protect_files.py: the hook's input is not JSON", file=sys.stderr)
        sys.exit(2)
    tool_input = data.get("tool_input") or {}
    file = tool_input.get("file_path") or tool_input.get("path") or ""
    if not file:
        return
    root = os.path.realpath(os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd())
    path = os.path.realpath(os.path.join(root, file))
    rel = os.path.relpath(path, root).replace(os.sep, "/")
    if rel.startswith("../"):
        return  # outside the project: not this hook's business
    if rel.endswith(".env.example"):
        return
    for patterns, reason in RULES:
        if any(fnmatch.fnmatchcase(rel, p) for p in patterns):
            print(f"Blocked by .claude/hooks/protect_files.py: {rel} - {reason}", file=sys.stderr)
            sys.exit(2)


if __name__ == "__main__":
    main()
