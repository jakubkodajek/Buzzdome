#!/usr/bin/env bash
# PreToolUse hook for Edit|Write: blocks edits to secrets, lockfiles, generated
# files and the reference manual copies. Exit code 2 blocks the call.
set -euo pipefail
# shellcheck source-path=SCRIPTDIR source=lib.sh
. "$(dirname "$0")/lib.sh"

file=$(hook_field "$(cat)" file_path path)
[ -z "$file" ] && exit 0
rel=${file#"${CLAUDE_PROJECT_DIR:-$PWD}/"}

block() {
  echo "Blocked by .claude/hooks/protect-files.sh: $rel - $1" >&2
  exit 2
}

case "$rel" in
  .env|.env.*|*/.env|*/.env.*)
    [[ "$rel" == *.env.example ]] || block "secret file; edit .env.example instead" ;;
  *.pem|*.key|*id_rsa*|*.p12|*.pfx)
    block "private key material" ;;
  Cargo.lock|app/package-lock.json|*/package-lock.json)
    block "lockfile; change it with cargo or npm, not by hand" ;;
  app/src/bindings/*)
    block "generated by ts-rs; change the Rust type and run cargo test --workspace" ;;
  .github/agents/*|.codex/agents/*|.agents/skills/*)
    block "generated file; edit .claude/agents or .claude/skills and run python3 scripts/sync_agents.py" ;;
  replica/sources/*|replica/screens/*|replica/captures/*|docs/index.md|docs/solo.md|docs/tips-and-tricks.md)
    block "reference manual copy or capture (clean room); never write or quote it" ;;
  docs/advanced/*|docs/analyzer/*|docs/assets/*|docs/hardware-installation/*|docs/installation/*|docs/javascripts/*|docs/legal/*|docs/live/*|docs/setup/*|docs/studio/*|docs/stylesheets/*)
    block "reference manual copy (clean room); our docs are the files directly in docs/ and docs/adr/" ;;
  .git/*)
    block "git internals" ;;
esac

exit 0
